#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn seed_sql_generates_inserts() {
        let brief = crate::product_engine::generate_product_brief(
            &crate::intent_engine::analyze_flat("wine marketplace"),
            "wine marketplace",
        );

        let spec = json!({
            "entities": [{
                "name": "Wine",
                "fields": [
                    {"name": "id", "type": "TEXT"},
                    {"name": "name", "type": "TEXT"},
                    {"name": "description", "type": "TEXT"},
                    {"name": "price", "type": "REAL"},
                    {"name": "region", "type": "TEXT"},
                ]
            }]
        });

        let sql = generate_seed_sql(&brief, &spec);
        assert!(sql.contains("INSERT OR IGNORE INTO Wine"));
        assert!(sql.contains("Chateau Margaux"));
        assert!(sql.contains("Opus One"));
    }

    #[test]
    fn seed_script_checks_for_existing_data() {
        let script = generate_seed_script("INSERT INTO wines (id, name) VALUES ('1', 'Test');");
        assert!(script.contains("SELECT COUNT(*)"));
        assert!(script.contains("Already has data"));
    }

    #[test]
    fn model_routing_uses_strong_for_ui() {
        let intent = crate::intent_engine::analyze_flat("wine app");
        assert_eq!(route_model_for_step("generate_ui", &intent), "gpt-4.1");
        assert_eq!(route_model_for_step("generate_api", &intent), "gpt-4.1-mini");
    }

    #[test]
    fn entity_matching_works() {
        let entities = vec![
            json!({"name": "Wine", "fields": [{"name": "id"}, {"name": "name"}]}),
            json!({"name": "Category", "fields": [{"name": "id"}, {"name": "title"}]}),
        ];
        assert!(find_matching_entity("featured", "Featured Collection", &entities).is_some());
        assert!(find_matching_entity("categories", "Explore by Region", &entities).is_some());
    }
}
