// 1. Parallel LLM Generation
// ---------------------------------------------------------------------------

/// Result of a parallel generation phase.
#[derive(Debug)]
pub struct ParallelGenResult {
    /// Files generated by each parallel step: (step_name, vec of (path, content))
    pub files: Vec<(String, Vec<(String, String)>)>,
    /// Steps that failed
    pub failures: Vec<(String, String)>,
    /// Total wall-clock time
    pub duration_ms: u64,
}

/// Run multiple LLM generation steps in parallel.
/// Returns all generated files from all steps.
///
/// Steps that fail are recorded but don't block other steps.
pub async fn run_parallel_generation(
    app: &Arc<AppState>,
    project_id: &str,
    prompts: Vec<(String, String)>, // (step_name, prompt)
    tx: &mpsc::Sender<PipelineEvent>,
) -> ParallelGenResult {
    let start = std::time::Instant::now();
    let mut handles = Vec::new();

    for (step_name, prompt) in prompts {
        let app_clone = app.clone();
        let pid = project_id.to_string();
        let sname = step_name.clone();
        let tx_clone = tx.clone();

        let handle = tokio::spawn(async move {
            let _ = tx_clone.send(PipelineEvent::Step {
                index: 0,
                name: sname.clone(),
                status: "running".into(),
                detail: format!("Generating {} (parallel)...", sname),
                duration_ms: None,
            }).await;

            let step_start = std::time::Instant::now();
            let result = call_with_retry(&app_clone, &pid, &prompt, 2).await;
            let dur = step_start.elapsed().as_millis() as u64;

            match result {
                Ok(response) => {
                    let files = nexus_store::parse_file_blocks(&response);
                    let _ = tx_clone.send(PipelineEvent::Step {
                        index: 0,
                        name: sname.clone(),
                        status: "completed".into(),
                        detail: format!("{} files generated in {}ms", files.len(), dur),
                        duration_ms: Some(dur),
                    }).await;
                    Ok((sname, files))
                }
                Err(e) => {
                    let _ = tx_clone.send(PipelineEvent::Step {
                        index: 0,
                        name: sname.clone(),
                        status: "failed".into(),
                        detail: e.clone(),
                        duration_ms: Some(dur),
                    }).await;
                    Err((sname, e))
                }
            }
        });

        handles.push(handle);
    }

    let mut files = Vec::new();
    let mut failures = Vec::new();

    for handle in handles {
        match handle.await {
            Ok(Ok((name, step_files))) => {
                files.push((name, step_files));
            }
            Ok(Err((name, error))) => {
                failures.push((name, error));
            }
            Err(e) => {
                failures.push(("unknown".into(), format!("Task panicked: {}", e)));
            }
        }
    }

    let duration_ms = start.elapsed().as_millis() as u64;

    info!(
        parallel_steps = files.len() + failures.len(),
        succeeded = files.len(),
        failed = failures.len(),
        duration_ms = duration_ms,
        "Parallel generation complete"
    );

    ParallelGenResult {
        files,
        failures,
        duration_ms,
    }
}

