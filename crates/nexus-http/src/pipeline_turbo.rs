// 2. Retry with Exponential Backoff
// ---------------------------------------------------------------------------

/// Call the LLM with retry logic. Retries on failure with exponential backoff.
pub async fn call_with_retry(
    app: &Arc<AppState>,
    project_id: &str,
    prompt: &str,
    max_retries: u32,
) -> Result<String, String> {
    let mut last_error = String::new();

    for attempt in 0..=max_retries {
        if attempt > 0 {
            let delay = Duration::from_millis(500 * 2u64.pow(attempt - 1));
            warn!(attempt = attempt, delay_ms = delay.as_millis(), "Retrying LLM call");
            tokio::time::sleep(delay).await;
        }

        match crate::handlers::chat::call_llm_simple_for_project(
            app,
            prompt,
            Some(project_id),
        )
        .await
        {
            Ok(response) => {
                // Validate response has actual content
                let trimmed = response.trim();
                if trimmed.is_empty() || trimmed.len() < 50 {
                    last_error = "LLM returned empty or very short response".into();
                    continue;
                }
                return Ok(response);
            }
            Err(e) => {
                last_error = e.to_string();
            }
        }
    }

    Err(format!("Failed after {} retries: {}", max_retries + 1, last_error))
}

