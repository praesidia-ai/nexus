/// Select the best model for a pipeline step based on complexity and purpose.
pub fn route_model_for_step(step: &str, _intent: &FlatIntent) -> &'static str {
    match step {
        // Strong model for spec generation (most critical — shapes everything)
        "generate_spec" => "gpt-4.1",
        // Strong model for UI (user-facing quality matters most)
        "generate_ui" => "gpt-4.1",
        // Medium model for API routes (structured, less creative)
        "generate_api" => "gpt-4.1-mini",
        // Medium model for auth (boilerplate-heavy)
        "generate_auth" => "gpt-4.1-mini",
        // Cheap model for validation (yes/no decisions)
        "validate_spec" => "gpt-4.1-mini",
        // Default
        _ => "gpt-4.1",
    }
}

