/// Generate SQL INSERT statements to populate the database with realistic seed data
/// from the product brief.
pub fn generate_seed_sql(brief: &ProductBrief, spec: &Value) -> String {
    let mut sql = String::from("-- Seed data generated by Nexus Product Engine\n\n");

    let entities = spec.get("entities")
        .and_then(|e| e.as_array())
        .cloned()
        .unwrap_or_default();

    for section in &brief.seed_content {
        // Try to match section to an entity
        let entity = find_matching_entity(&section.section_id, &section.title, &entities);
        let Some(entity) = entity else { continue };

        let entity_name = entity.get("name").and_then(|n| n.as_str()).unwrap_or("items");
        let fields = entity.get("fields")
            .and_then(|f| f.as_array())
            .cloned()
            .unwrap_or_default();

        let field_names: Vec<String> = fields.iter()
            .filter_map(|f| f.get("name").and_then(|n| n.as_str()))
            .filter(|n| *n != "id" && *n != "created_at")
            .map(String::from)
            .collect();

        if field_names.is_empty() { continue; }

        sql.push_str(&format!("-- {} seed data\n", entity_name));

        for item in &section.items {
            let id = uuid::Uuid::new_v4().to_string();

            // Map content item fields to entity fields
            let mut values: Vec<String> = Vec::new();
            let mut columns: Vec<String> = vec!["id".into()];
            values.push(format!("'{}'", id));

            for field_name in &field_names {
                let lower = field_name.to_lowercase();
                let val = if lower.contains("name") || lower.contains("title") {
                    Some(item.name.clone())
                } else if lower.contains("desc") || lower.contains("summary") || lower.contains("detail") {
                    Some(item.description.clone())
                } else if lower.contains("price") || lower.contains("cost") || lower.contains("amount") {
                    item.price.as_ref().map(|p| p.replace('$', "").replace("/mo", "").replace("/night", ""))
                } else if lower.contains("category") || lower.contains("type") || lower.contains("region") {
                    Some(item.detail.clone())
                } else if lower.contains("badge") || lower.contains("tag") || lower.contains("label") {
                    item.badge.clone()
                } else if lower.contains("image") || lower.contains("icon") || lower.contains("emoji") {
                    Some(item.image_emoji.clone())
                } else {
                    None
                };

                if let Some(v) = val {
                    columns.push(field_name.clone());
                    values.push(format!("'{}'", v.replace('\'', "''")));
                }
            }

            sql.push_str(&format!(
                "INSERT OR IGNORE INTO {} ({}) VALUES ({});\n",
                entity_name,
                columns.join(", "),
                values.join(", "),
            ));
        }

        sql.push('\n');
    }

    sql
}

/// Try to match a content section to a database entity.
fn find_matching_entity<'a>(section_id: &str, section_title: &str, entities: &'a [Value]) -> Option<&'a Value> {
    let lower_id = section_id.to_lowercase();
    let lower_title = section_title.to_lowercase();

    for entity in entities {
        let name = entity.get("name").and_then(|n| n.as_str()).unwrap_or("").to_lowercase();

        // Direct name match
        if name == lower_id || lower_id.contains(&name) || name.contains(&lower_id) {
            return Some(entity);
        }

        // Singular/plural match: "categories" matches "category", "wines" matches "wine"
        let name_singular = name.trim_end_matches('s');
        let id_singular = lower_id.trim_end_matches("ies").to_string() + if lower_id.ends_with("ies") { "y" } else { "" };
        let id_singular = if id_singular == lower_id { lower_id.trim_end_matches('s').to_string() } else { id_singular };
        if name_singular == id_singular || name == id_singular || name_singular == lower_id {
            return Some(entity);
        }

        // Title-based match
        if lower_title.contains(&name) {
            return Some(entity);
        }
    }

    // Fallback: match common section IDs to first entity
    if matches!(lower_id.as_str(), "featured" | "products" | "listings" | "menu" | "programs") {
        return entities.first();
    }

    None
}

/// Generate a seed data script that runs on app startup.
pub fn generate_seed_script(seed_sql: &str) -> String {
    if seed_sql.trim().is_empty() || seed_sql.lines().all(|l| l.starts_with("--") || l.trim().is_empty()) {
        return String::new();
    }

    format!(
        r#"import {{ getDb }} from './index';

// Seed the database with sample data on first run
export function seedDatabase() {{
  const db = getDb();
  const count = db.prepare('SELECT COUNT(*) as c FROM sqlite_master WHERE type="table"').get() as {{ c: number }};
  if (count.c === 0) return; // No tables yet

  // Check if already seeded
  try {{
    const tables = db.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'").all() as {{ name: string }}[];
    for (const table of tables) {{
      const rowCount = db.prepare(`SELECT COUNT(*) as c FROM ${{table.name}}`).get() as {{ c: number }};
      if (rowCount.c > 0) return; // Already has data
    }}
  }} catch {{
    return;
  }}

  // Insert seed data
  db.exec(`
{seed_sql}  `);

  console.log('Database seeded with sample data');
}}

// Auto-seed on import
seedDatabase();
"#
    )
}

