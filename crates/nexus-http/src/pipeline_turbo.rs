/// Wait for a dev server to become healthy, with timeout.
pub async fn wait_for_health(port: u32, timeout_secs: u64) -> bool {
    let url = format!("http://localhost:{}", port);
    let client = reqwest::Client::builder()
        .timeout(Duration::from_secs(3))
        .build()
        .unwrap_or_default();

    let deadline = std::time::Instant::now() + Duration::from_secs(timeout_secs);

    while std::time::Instant::now() < deadline {
        match client.get(&url).send().await {
            Ok(resp) if resp.status().is_success() || resp.status().as_u16() == 404 => {
                // 404 is OK — Next.js is running but maybe no root page yet
                info!(port = port, "App health check passed");
                return true;
            }
            _ => {
                tokio::time::sleep(Duration::from_secs(2)).await;
            }
        }
    }

    warn!(port = port, "App health check timed out");
    false
}

